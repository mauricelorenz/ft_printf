#include "libft.h"

int	ft_putnbr_count(int n)
{
	int	i;

	i = 0;
	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return (11);
	}
	if (n < 0)
	{
		write(1, "-", 1);
		i++;
		n = (-n);
	}
	if (n >= 10)
		i += ft_putnbr_count(n / 10);
	n = n % 10 + '0';
	write(1, &n, 1);
	return (i + 1);
}
